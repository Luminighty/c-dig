function ReadHeaderIntoFFI(filename)
	local file = assert(io.open(filename))
	local is_inside_directive = false
	for line in file:lines() do
		local is_directive = string.match(line, "^%s*#")
		if is_directive or is_inside_directive then
			is_directive = is_directive or is_inside_directive
			is_inside_directive = string.match(line, "\\%s*$")
		end

		local is_comment = string.match(line, "^%s*//")

		local is_included = not is_directive and not is_comment
		if is_included then
			io.write(line)
			io.write("\n")
		end
	end
end
